type starterColRule struct {
	Column   string       `yaml:"column"`
	Strategy pii.Strategy `yaml:"strategy"`
}

// GenerateStarterConfig synthesizes a complete, commented, ready-to-run pgveil.yaml
// from a live discover.Scan report and the scanned PostgreSQL DSN.
func GenerateStarterConfig(report *Report, dsn string) (string, error) {
	if report == nil {
		return "", fmt.Errorf("discovery report cannot be nil")
	}

	hostPort, user, password, database, tlsEnabled := parseUpstreamDSN(dsn, report.Database)

	secretBytes := make([]byte, 24)
	if _, err := rand.Read(secretBytes); err != nil {
		return "", fmt.Errorf("generate masking secret: %w", err)
	}
	maskingSecret := "pgveil_" + hex.EncodeToString(secretBytes)

	// Deduplicate discovered column rules, protected columns, and active compliance packs.
	seenCols := make(map[string]bool)
	packSet := make(map[string]bool)
	var colRules []starterColRule
	var protectedCols []string

	for _, f := range report.Findings {
		for _, p := range f.CompliancePacks {
			packSet[p] = true
		}
		low := strings.ToLower(f.Column)
		if low == "body" || low == "shipping_note" || low == "notes" || low == "description" {
			continue
		}
		if seenCols[low] {
			continue
		}
		seenCols[low] = true
		colRules = append(colRules, starterColRule{Column: f.Column, Strategy: f.RecommendedStrategy})
		if f.RiskLevel == "CRITICAL" || f.RiskLevel == "HIGH" {
			protectedCols = append(protectedCols, f.Column)
		}
	}

	packs := make([]string, 0, len(packSet))
	for p := range packSet {
		packs = append(packs, p)
	}
	if len(packs) == 0 {
		packs = []string{"gdpr", "kvkk", "pci-dss", "hipaa", "secrets"}
	}
	sort.Strings(packs)

	deniedTables := append([]string{}, report.RecommendedTables...)
	for _, sysTbl := range []string{"pg_shadow", "pg_authid", "pg_roles"} {
		found := false
		for _, dt := range deniedTables {
			if strings.EqualFold(dt, sysTbl) {
				found = true
				break
			}
		}
		if !found {
			deniedTables = append(deniedTables, sysTbl)
		}
	}

	var sb strings.Builder
	fmt.Fprintf(&sb, "# pgveil — Auto-generated Zero-Trust Policy Configuration\n")
	fmt.Fprintf(&sb, "# Generated by `pgveil init` from database %q (%d tables scanned, %d PII/secret findings)\n",
		database, report.TablesScanned, report.FindingsCount)
	fmt.Fprintf(&sb, "# Start proxy:  pgveil serve --config pgveil.yaml\n")
	fmt.Fprintf(&sb, "# Validate:     pgveil validate --config pgveil.yaml\n\n")

	fmt.Fprintf(&sb, "server:\n")
	fmt.Fprintf(&sb, "  listen_addr: \":6432\"\n")
	fmt.Fprintf(&sb, "  admin_addr: \":8088\"\n")
	fmt.Fprintf(&sb, "  upstream_addr: %s\n", yamlQuote(hostPort))
	fmt.Fprintf(&sb, "  upstream_user: %s\n", yamlQuote(user))
	fmt.Fprintf(&sb, "  upstream_password: %s # Override in production with PGVEIL_UPSTREAM_PASSWORD\n", yamlQuote(password))
	fmt.Fprintf(&sb, "  upstream_database: %s\n", yamlQuote(database))
	fmt.Fprintf(&sb, "  tls:\n")
	fmt.Fprintf(&sb, "    enabled: false\n")
	fmt.Fprintf(&sb, "    cert_file: \"\"\n")
	fmt.Fprintf(&sb, "    key_file: \"\"\n")
	fmt.Fprintf(&sb, "  upstream_tls:\n")
	fmt.Fprintf(&sb, "    enabled: %v\n", tlsEnabled)
	fmt.Fprintf(&sb, "    insecure_skip_verify: false\n")
	fmt.Fprintf(&sb, "    server_name: \"\"\n\n")

	fmt.Fprintf(&sb, "notifications:\n")
	fmt.Fprintf(&sb, "  webhook_url: \"\"\n\n")

	fmt.Fprintf(&sb, "security:\n")
	fmt.Fprintf(&sb, "  masking_secret: %s # Auto-generated HMAC key; override via PGVEIL_MASKING_SECRET\n", yamlQuote(maskingSecret))
	fmt.Fprintf(&sb, "  hitl_default_timeout: \"60s\"\n")
	fmt.Fprintf(&sb, "  compliance_packs:\n")
	for _, p := range packs {
		fmt.Fprintf(&sb, "    - %s\n", p)
	}
	fmt.Fprintf(&sb, "\n")

	fmt.Fprintf(&sb, "telemetry:\n")
	fmt.Fprintf(&sb, "  service_name: \"pgveil-proxy\"\n")
	fmt.Fprintf(&sb, "  prometheus_enabled: true\n")
	fmt.Fprintf(&sb, "  otel_enabled: false\n")
	fmt.Fprintf(&sb, "  otel_endpoint: \"localhost:4317\"\n\n")

	fmt.Fprintf(&sb, "kafka:\n")
	fmt.Fprintf(&sb, "  enabled: false\n")
	fmt.Fprintf(&sb, "  brokers:\n")
	fmt.Fprintf(&sb, "    - \"localhost:9092\"\n")
	fmt.Fprintf(&sb, "  audit_topic: \"pgveil.audit.queries\"\n")
	fmt.Fprintf(&sb, "  alerts_topic: \"pgveil.alerts.security\"\n")
	fmt.Fprintf(&sb, "  dlq_topic: \"pgveil.audit.dlq\"\n")
	fmt.Fprintf(&sb, "  client_id: \"pgveil-proxy\"\n\n")

	fmt.Fprintf(&sb, "default_profile: \"analyst\"\n\n")
	fmt.Fprintf(&sb, "profiles:\n")
	fmt.Fprintf(&sb, "  - name: \"ai_agent\"\n")
	fmt.Fprintf(&sb, "    description: \"Zero-trust sandbox for AI SQL agents, Claude Code, Cursor, and MCP Postgres servers.\"\n")
	fmt.Fprintf(&sb, "    mode: \"enforce\"\n")
	fmt.Fprintf(&sb, "    match:\n")
	fmt.Fprintf(&sb, "      application_names: [\"ai_agent\", \"claude-mcp*\", \"cursor*\", \"langchain*\", \"mcp-postgres*\"]\n")
	fmt.Fprintf(&sb, "      users: [\"ai_agent\", \"mcp_readonly\"]\n")
	fmt.Fprintf(&sb, "    firewall:\n")
	fmt.Fprintf(&sb, "      allow_statements: [\"SELECT\", \"EXPLAIN\", \"SHOW\"]\n")
	fmt.Fprintf(&sb, "      block_ddl: true\n")
	fmt.Fprintf(&sb, "      block_multi_statement: true\n")
	fmt.Fprintf(&sb, "      block_write_without_where: true\n")
	fmt.Fprintf(&sb, "      block_dangerous_functions: true\n")
	fmt.Fprintf(&sb, "      block_system_catalogs: true\n")
	fmt.Fprintf(&sb, "      block_pii_inference: true\n")
	fmt.Fprintf(&sb, "      protected_columns: %s\n", yamlInlineStringList(protectedCols))
	fmt.Fprintf(&sb, "      require_hitl_statements: [\"UPDATE\", \"DELETE\", \"INSERT\"]\n")
	fmt.Fprintf(&sb, "      hitl_mode: \"hold\"\n")
	fmt.Fprintf(&sb, "      hitl_timeout: \"60s\"\n")
	fmt.Fprintf(&sb, "      denied_tables: %s\n", yamlInlineStringList(deniedTables))
	fmt.Fprintf(&sb, "      # Optional AST-level Virtual Row-Level Security (RLS) tenant isolation:\n")
	fmt.Fprintf(&sb, "      # row_filters:\n")
	fmt.Fprintf(&sb, "      #   - table: \"customers\"\n")
	fmt.Fprintf(&sb, "      #     predicate: \"tenant_id = '{{db_user}}'\"\n")
	fmt.Fprintf(&sb, "      max_rows: 25\n")
	fmt.Fprintf(&sb, "      max_rows_action: \"truncate\"\n")
	fmt.Fprintf(&sb, "    masking:\n")
	fmt.Fprintf(&sb, "      enabled: true\n")
	fmt.Fprintf(&sb, "      auto_detect_pii: true\n")
	fmt.Fprintf(&sb, "      compliance_packs: %s\n", yamlInlineStringList(packs))
	writeColumnRulesYAML(&sb, colRules)

	fmt.Fprintf(&sb, "\n  - name: \"analyst\"\n")
	fmt.Fprintf(&sb, "    description: \"Read-only BI & analytics profile with pseudonymization and 500-row budget.\"\n")
	fmt.Fprintf(&sb, "    match:\n")
	fmt.Fprintf(&sb, "      application_names: [\"analyst*\", \"metabase*\", \"superset*\", \"dbeaver*\"]\n")
	fmt.Fprintf(&sb, "      users: [\"analyst\", \"bi_reader\"]\n")
	fmt.Fprintf(&sb, "    firewall:\n")
	fmt.Fprintf(&sb, "      allow_statements: [\"SELECT\", \"EXPLAIN\", \"SHOW\"]\n")
	fmt.Fprintf(&sb, "      block_ddl: true\n")
	fmt.Fprintf(&sb, "      block_multi_statement: true\n")
	fmt.Fprintf(&sb, "      block_write_without_where: true\n")
	fmt.Fprintf(&sb, "      block_dangerous_functions: true\n")
	fmt.Fprintf(&sb, "      block_system_catalogs: true\n")
	fmt.Fprintf(&sb, "      denied_tables: %s\n", yamlInlineStringList(deniedTables))
	fmt.Fprintf(&sb, "      max_rows: 500\n")
	fmt.Fprintf(&sb, "      max_rows_action: \"truncate\"\n")
	fmt.Fprintf(&sb, "    masking:\n")
	fmt.Fprintf(&sb, "      enabled: true\n")
	fmt.Fprintf(&sb, "      auto_detect_pii: true\n")
	fmt.Fprintf(&sb, "      compliance_packs: %s\n", yamlInlineStringList(packs))
	writeColumnRulesYAML(&sb, colRules)

	fmt.Fprintf(&sb, "\n  - name: \"admin\"\n")
	fmt.Fprintf(&sb, "    description: \"Break-glass DBA profile: full unmasked access with full audit trail.\"\n")
	fmt.Fprintf(&sb, "    match:\n")
	fmt.Fprintf(&sb, "      application_names: [\"admin*\", \"pgveil-admin*\"]\n")
	fmt.Fprintf(&sb, "      users: [\"admin\", \"dba\"]\n")
	fmt.Fprintf(&sb, "    firewall:\n")
	fmt.Fprintf(&sb, "      allow_statements: [\"*\"]\n")
	fmt.Fprintf(&sb, "      block_ddl: false\n")
	fmt.Fprintf(&sb, "      block_multi_statement: false\n")
	fmt.Fprintf(&sb, "      block_write_without_where: false\n")
	fmt.Fprintf(&sb, "      block_dangerous_functions: false\n")
	fmt.Fprintf(&sb, "      block_system_catalogs: false\n")
	fmt.Fprintf(&sb, "      max_rows: 0\n")
	fmt.Fprintf(&sb, "    masking:\n")
	fmt.Fprintf(&sb, "      enabled: false\n")
	fmt.Fprintf(&sb, "      auto_detect_pii: false\n")

	return sb.String(), nil
}

func parseUpstreamDSN(dsn, fallbackDB string) (hostPort, user, password, db string, tlsEnabled bool) {
	hostPort = "127.0.0.1:5432"
	user = "postgres"
	db = fallbackDB
	if db == "" {
		db = "postgres"
	}

	u, err := url.Parse(strings.TrimSpace(dsn))
	if err != nil || u.Host == "" {
		return hostPort, user, password, db, tlsEnabled
	}
	host := u.Hostname()
	port := u.Port()
	if host == "" {
		host = "127.0.0.1"
	}
	if port == "" {
		port = "5432"
	}
	hostPort = net.JoinHostPort(host, port)
	if u.User != nil {
		if un := u.User.Username(); un != "" {
			user = un
		}
		if pw, ok := u.User.Password(); ok {
			password = pw
		}
	}
	if p := strings.TrimPrefix(u.Path, "/"); p != "" {
		db = p
	}
	sslMode := strings.ToLower(u.Query().Get("sslmode"))
	if sslMode == "require" || sslMode == "verify-ca" || sslMode == "verify-full" {
		tlsEnabled = true
	}
	return hostPort, user, password, db, tlsEnabled
}

func yamlQuote(s string) string {
	b, err := yaml.Marshal(s)
	if err != nil {
		return fmt.Sprintf("%q", s)
	}
	trimmed := strings.TrimSpace(string(b))
	if !strings.HasPrefix(trimmed, `"`) && !strings.HasPrefix(trimmed, `'`) {
		return fmt.Sprintf("%q", s)
	}
	return trimmed
}

func yamlInlineStringList(items []string) string {
	if len(items) == 0 {
		return "[]"
	}
	quoted := make([]string, len(items))
	for i, it := range items {
		quoted[i] = fmt.Sprintf("%q", it)
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}

func writeColumnRulesYAML(sb *strings.Builder, rules []starterColRule) {
	if len(rules) == 0 {
		fmt.Fprintf(sb, "      column_rules: []\n")
		return
	}
	fmt.Fprintf(sb, "      column_rules:\n")
	for _, r := range rules {
		fmt.Fprintf(sb, "        - column: %q\n", r.Column)
		fmt.Fprintf(sb, "          strategy: %q\n", string(r.Strategy))
	}
}
